import "server-only";
import { MCPServerStreamableHttp } from "@openai/agents";
import { ApiError, logError } from "./errors";
import { RESEARCH_AGENT_BUDGET } from "./agent-budget";

type ReportProgress = (type: string, message: string, payload: { tool: string }) => Promise<unknown>;

const toolLabels: Record<string, string> = {
  create_research_package: "创建研究计划",
  search_scenario: "检索并整理证据",
  generate_workspace: "生成工作区文件",
  update_file_plan: "更新文件计划",
  ask_user: "整理澄清问题",
  get_user_answers: "读取澄清答案",
  read_workspace_file: "读取工作区文件",
  write_workspace_file: "保存工作区文件",
  export_workspace: "导出工作区",
  search_evidence: "检索项目证据",
  get_evidence: "查看证据原文",
  get_file_context: "检索文件上下文",
  get_research_package: "读取研究状态",
  update_workspace_file: "更新工作区文件",
};

export class ScopedMcpServer extends MCPServerStreamableHttp {
  private toolCalls = 0;

  constructor(private packageId: string, url: string, private report: ReportProgress) {
    super({
      url,
      name: "ScenarioForge",
      cacheToolsList: true,
      clientSessionTimeoutSeconds: 660,
      // Tool requests otherwise override the session timeout with the SDK's
      // 60-second default while Python is waiting for a model response.
      timeout: 660_000,
      // Stop the worker on failure instead of asking the model to retry a tool.
      errorFunction: null,
    });
  }

  override async listTools() {
    // Submitting a user's answer is reserved for the UI/CLI. The research Agent
    // must wait for the user rather than answering its own blocking questions.
    const tools = (await super.listTools()).filter(tool => tool.name !== "answer_user");
    // The package already owns the user's goal, constraints and uploads. Give
    // the planner a closed schema instead of inviting it to invent plan fields.
    return tools.map((tool) => tool.name === "create_research_package" ? {
      ...tool,
      description: "Create or reuse the current package's research and file plan. Pass only package_id; goal, constraints and uploaded files are read from the saved package. Research questions and the file plan are generated by this tool, not input arguments.",
      inputSchema: {
        type: "object" as const,
        properties: { package_id: { type: "string", description: "The current research package ID" } },
        required: ["package_id"],
        additionalProperties: false,
      },
    } : tool.name === "search_scenario" ? {
      ...tool,
      description: "Search the saved research question identified by its zero-based question_index in researchPlan.researchQuestions. Do not rewrite question text. Completed questions reuse saved evidence without spending search budget; when all are done, generate_workspace.",
      inputSchema: {
        type: "object" as const,
        properties: {
          package_id: { type: "string" },
          question_index: { type: "integer", minimum: 0, maximum: 5, description: "Zero-based index in the saved researchPlan.researchQuestions array." },
          max_results: { type: ["integer", "null"], minimum: 1, maximum: 20 },
        },
        required: ["package_id", "question_index"],
        additionalProperties: false,
      },
    } : tool);
  }

  override async callToolResult(...args: Parameters<MCPServerStreamableHttp["callToolResult"]>) {
    if (args[0] === "answer_user") throw new ApiError(403, "研究 Agent 不可代替用户回答澄清问题。");
    if (this.toolCalls >= RESEARCH_AGENT_BUDGET.maxToolCalls) throw new ApiError(429, "本轮研究工具调用已达到上限，已停止以控制开销。");
    this.toolCalls++;
    args[1] = args[0] === "create_research_package"
      ? { package_id: this.packageId }
      : { ...args[1], package_id: this.packageId };
    const label = toolLabels[args[0]] ?? "执行研究工具";
    const payload = { tool: args[0] };
    await this.report("tool_started", `正在${label}，请稍候…`, payload);
    try {
      const result = await super.callToolResult(...args);
      if (result.isError) throw new ApiError(502, `${label}失败，请检查 MCP 服务日志后再继续研究。本轮已停止，避免重复调用模型。`);
      {
        let output = result.structuredContent;
        if (!output) {
          const text = result.content.find((item) => item.type === "text");
          if (text?.type === "text" && typeof text.text === "string") {
            try { output = JSON.parse(text.text); } catch { /* Non-JSON tool output. */ }
          }
        }
        if (args[0] === "search_scenario" && output?.status === "search_unavailable") {
          const reason = typeof output.message === "string" ? output.message.slice(0, 500) : "搜索未获得有效证据，请检查搜索配置。";
          throw new ApiError(502, `${label}失败：${reason} 本轮已停止，避免重复调用模型。`);
        }
        if (output?.status === "generation_failed" || output?.status === "planning_failed") {
          const reason = typeof output.message === "string" ? output.message.slice(0, 500) : output.status === "planning_failed" ? "研究计划未生成，请检查模型配置或目标要求。" : "文件生成未完成，已保留现有文件。";
          const filename = typeof output.filename === "string" && /^[A-Za-z][A-Za-z0-9_-]{0,79}\.md$/.test(output.filename) ? `（${output.filename}）` : "";
          throw new ApiError(502, `${label}失败${filename}：${reason} 本轮已停止。`);
        }
      }
      await this.report("tool_completed", `${label}工具执行结束`, payload);
      return result;
    } catch (error) {
      const failure = error instanceof ApiError ? error : new ApiError(502,
        args[3]?.signal?.aborted ? `${label}已取消，本轮研究已停止。`
          : error instanceof Error && /timeout|timed out/i.test(error.message)
            ? `${label}等待超时，本轮已停止，避免重复调用模型。请检查模型服务响应速度后再继续研究。`
            : `${label}的工具连接失败，本轮已停止，避免重复调用模型。请检查 MCP 服务后再继续研究。`);
      if (!(error instanceof ApiError) && !args[3]?.signal?.aborted) logError(error);
      await this.report("tool_failed", failure.message, payload);
      throw failure;
    }
  }
}
