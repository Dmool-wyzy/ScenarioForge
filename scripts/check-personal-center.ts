type Actor = { id: string; token: string };
function req(actor: Actor | null, method = "GET", body?: unknown, query = "") {
  return new Request(`http://localhost/api/me/profile${query}`, { method, headers: { Origin: "http://localhost", "Content-Type": "application/json", ...(actor ? { Cookie: `scenarioforge_session=${actor.token}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
}
